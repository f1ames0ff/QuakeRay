"""Inspect and enforce GPL v2+ copyright headers on QuakeRay files."""

from __future__ import annotations

import argparse
from datetime import datetime
from pathlib import Path
import re
import subprocess
import sys

DEFAULT_BASE = "origin/master"
DEFAULT_AUTHOR = "f1ames0ff <f1am3sdev.github@protonmail.com>"

SLASH_EXTS = frozenset({
    ".c", ".cc", ".cpp", ".cxx",
    ".h", ".hh", ".hpp", ".hxx", ".inl",
    ".hlsl", ".hlsli", ".glsl", ".vert", ".frag", ".comp", ".rgen", ".rmiss", ".rchit", ".rahit",
})
HASH_EXTS = frozenset({".py", ".sh", ".ps1"})
SUPPORTED_EXTS = SLASH_EXTS | HASH_EXTS

EXCLUDE_PREFIXES = (
    "third_party/",
    "renderer/",
    "Windows/",
    "MacOSX/",
    "Quake/mimalloc/",
    "tools/quakeray_mcp/.venv/",
    "build/",
    "build-",
)
THIRD_PARTY_FILES = frozenset({
    "Quake/miniz.h",
    "Quake/miniz.c",
    "Quake/stb_image.h",
    "Quake/stb_image_resize.h",
    "Quake/stb_image_write.h",
})
LEGACY_UPSTREAM_FILES = frozenset({
    "Misc/systest.c",
    "Quake/default_cfg.h",
    "Quake/qs_bmp.h",
    "Quake/snd_flac.h",
    "Quake/snd_mikmod.h",
    "Quake/snd_modplug.h",
    "Quake/snd_mp3.h",
    "Quake/snd_opus.h",
    "Quake/snd_umx.h",
    "Quake/snd_vorbis.h",
    "Quake/snd_wave.h",
    "Quake/snd_xmp.h",
    "Quake/strl_fn.h",
    "Quake/wsaerror.h",
})
LEGACY_EXCLUDED_FILES = THIRD_PARTY_FILES | LEGACY_UPSTREAM_FILES

_HEADER_MARKERS = (
    "copyright",
    "gnu general public license",
    "spdx-license-identifier",
    "f1ames0ff",
)
_GENERATED_MARKERS = (
    "generated by",
    "do not edit",
    "@generated",
)
_CODING_RE = re.compile(r"^[ \t]*#.*?coding[:=][ \t]*[-\w.]+")
_PS_REQUIRES_RE = re.compile(r"^[ \t]*#requires\b", re.IGNORECASE)


def norm_rel(path_str: str, repo_root: Path) -> str:
    """Normalize a path into a POSIX path relative to repo_root when inside it."""
    raw = path_str.replace("\\", "/")
    candidate = Path(raw)
    root_resolved = repo_root.resolve()
    target = candidate.resolve() if candidate.is_absolute() else (repo_root / raw).resolve()
    try:
        return target.relative_to(root_resolved).as_posix()
    except ValueError:
        return candidate.as_posix() if candidate.is_absolute() else raw.lstrip("./")


def is_excluded(rel_path: str) -> bool:
    """Return True if a repo-relative path belongs to third-party, upstream legacy, or build trees."""
    norm = rel_path.replace("\\", "/").lstrip("./")
    if norm in LEGACY_EXCLUDED_FILES:
        return True
    return any(norm == prefix.rstrip("/") or norm.startswith(prefix) for prefix in EXCLUDE_PREFIXES)


def is_eligible_path(rel_path: str) -> bool:
    """Return True if a repo-relative path is a supported non-excluded source/script file."""
    return Path(rel_path).suffix.lower() in SUPPORTED_EXTS and not is_excluded(rel_path)


def comment_prefix_for(suffix: str) -> str | None:
    """Return the line-comment token for a supported file extension, or None."""
    low = suffix.lower()
    if low in SLASH_EXTS:
        return "//"
    if low in HASH_EXTS:
        return "#"
    return None


def _header_probe_text(text: str) -> str:
    clean = text.removeprefix("\ufeff")
    head_chars = clean[:2500]
    head_lines = "\n".join(clean.splitlines()[:35])
    return (head_lines if len(head_lines) > len(head_chars) else head_chars).lower()


def has_copyright_header(text: str) -> bool:
    """Return True if text already starts with a copyright or license header."""
    probe = _header_probe_text(text)
    return any(marker in probe for marker in _HEADER_MARKERS)


def is_generated_file(text: str) -> bool:
    """Return True if the file header marks it as machine-generated."""
    clean = text.removeprefix("\ufeff")
    probe = "\n".join(clean.splitlines()[:5]).lower()
    return any(marker in probe for marker in _GENERATED_MARKERS)


def build_header_lines(prefix: str, *, year: int, author: str, newline: str) -> list[str]:
    """Render the standard GPL v2+ copyright header lines with line endings."""
    body = [
        f"Copyright (c) {year} {author}",
        "",
        "This program is free software; you can redistribute it and/or modify",
        "it under the terms of the GNU General Public License as published by",
        "the Free Software Foundation; either version 2 of the License, or",
        "(at your option) any later version.",
        "",
        "This program is distributed in the hope that it will be useful,",
        "but WITHOUT ANY WARRANTY; without even the implied warranty of",
        "MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the",
        "GNU General Public License for more details.",
        "",
        "You should have received a copy of the GNU General Public License along",
        "with this program; if not, write to the Free Software Foundation, Inc.,",
        "51 Franklin Street, Fifth Floor, Boston, MA 02110-1301 USA.",
        "",
    ]
    return [f"{prefix} {line}{newline}" if line else f"{prefix}{newline}" for line in body]


def _find_insertion_line(lines: list[str], suffix: str) -> int:
    low = suffix.lower()
    if lines and lines[0].startswith("#!"):
        if low == ".py" and len(lines) > 1 and _CODING_RE.match(lines[1]):
            return 2
        return 1
    if low == ".py" and lines and _CODING_RE.match(lines[0]):
        return 1
    if low == ".ps1":
        for idx, line in enumerate(lines):
            if not line.strip():
                continue
            if _PS_REQUIRES_RE.match(line):
                return idx + 1
            break
    return 0


def insert_header(
    raw_bytes: bytes,
    suffix: str,
    *,
    year: int | None = None,
    author: str = DEFAULT_AUTHOR,
) -> bytes | None:
    """Return updated UTF-8 bytes with copyright header inserted, or None if no change needed."""
    prefix = comment_prefix_for(suffix)
    if prefix is None:
        return None
    try:
        text = raw_bytes.decode("utf-8")
    except UnicodeDecodeError:
        return None
    if has_copyright_header(text) or is_generated_file(text):
        return None

    resolved_year = datetime.now().year if year is None else year
    has_bom = text.startswith("\ufeff")
    body = text[1:] if has_bom else text
    newline = "\r\n" if "\r\n" in body else "\n"
    bom_prefix = "\ufeff" if has_bom else ""
    header_lines = build_header_lines(prefix, year=resolved_year, author=author, newline=newline)

    if not body.strip():
        return (bom_prefix + "".join(header_lines)).encode("utf-8")

    lines = body.splitlines(keepends=True)
    idx = _find_insertion_line(lines, suffix)
    head = list(lines[:idx])
    tail = lines[idx:]
    if head and not head[-1].endswith(("\n", "\r")):
        head[-1] = head[-1] + newline
    spacer = [newline] if tail and tail[0].strip() else []
    updated = bom_prefix + "".join([*head, *header_lines, *spacer, *tail])
    return updated.encode("utf-8")


def _run_git(repo_root: Path, args: list[str], *, check: bool = True) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(
        ["git", "-C", str(repo_root), *args],
        capture_output=True,
        check=check,
    )


def _split_nul_paths(payload: bytes) -> list[str]:
    return [p.decode("utf-8", errors="replace").replace("\\", "/") for p in payload.split(b"\0") if p]


def collect_all_tracked_files(repo_root: Path) -> list[str]:
    """Return all tracked eligible repo-relative file paths."""
    res = _run_git(repo_root, ["ls-files", "-z"])
    return sorted(p for p in _split_nul_paths(res.stdout) if is_eligible_path(p))


def collect_staged_added_files(repo_root: Path) -> list[str]:
    """Return staged newly added eligible repo-relative file paths."""
    res = _run_git(repo_root, ["diff", "--cached", "--name-only", "--diff-filter=A", "-z"])
    return sorted(p for p in _split_nul_paths(res.stdout) if is_eligible_path(p))


def collect_added_files(repo_root: Path, base_ref: str, local: bool) -> list[str]:
    """Return newly added eligible repo-relative file paths for local or branch diff mode."""
    found: set[str] = set()
    if local:
        diff_res = _run_git(repo_root, ["diff", "--name-only", "--diff-filter=A", "-z", "HEAD"])
        found.update(_split_nul_paths(diff_res.stdout))
        untracked = _run_git(repo_root, ["ls-files", "--others", "--exclude-standard", "-z"])
        found.update(_split_nul_paths(untracked.stdout))
    else:
        diff_res = _run_git(repo_root, ["diff", "--name-only", "--diff-filter=A", "-z", f"{base_ref}...HEAD"])
        found.update(_split_nul_paths(diff_res.stdout))
    return sorted(p for p in found if is_eligible_path(p))


def needs_copyright_header(repo_root: Path, rel_path: str) -> bool:
    """Return True if an eligible on-disk file is missing a copyright header."""
    if not is_eligible_path(rel_path):
        return False
    full = repo_root / rel_path
    if not full.is_file() or full.is_symlink():
        return False
    try:
        text = full.read_bytes().decode("utf-8")
    except UnicodeDecodeError:
        return False
    return not has_copyright_header(text) and not is_generated_file(text)


def find_missing_copyright_files(repo_root: Path, rel_paths: list[str]) -> list[str]:
    """Filter rel_paths down to eligible files missing a copyright header."""
    return [rel for rel in sorted(set(rel_paths)) if needs_copyright_header(repo_root, rel)]


def fix_files(
    repo_root: Path,
    rel_paths: list[str],
    *,
    year: int | None = None,
    author: str = DEFAULT_AUTHOR,
) -> list[str]:
    """Insert missing copyright headers in place; return list of modified relative paths."""
    modified: list[str] = []
    for rel in sorted(set(rel_paths)):
        if not is_eligible_path(rel):
            continue
        full = repo_root / rel
        if not full.is_file() or full.is_symlink():
            continue
        raw = full.read_bytes()
        updated = insert_header(raw, full.suffix, year=year, author=author)
        if updated is not None and updated != raw:
            full.write_bytes(updated)
            modified.append(rel)
    return modified


def _staged_matches_worktree(repo_root: Path, rel_path: str) -> bool:
    blob_res = _run_git(repo_root, ["cat-file", "blob", f":{rel_path}"], check=False)
    if blob_res.returncode != 0:
        return False
    full = repo_root / rel_path
    if not full.is_file() or full.is_symlink():
        return False
    if blob_res.stdout == full.read_bytes():
        return True
    diff_res = _run_git(repo_root, ["diff", "--quiet", "--", rel_path], check=False)
    return diff_res.returncode == 0


def handle_staged(repo_root: Path, *, year: int | None = None, author: str = DEFAULT_AUTHOR) -> int:
    """Ensure every staged newly added eligible file has a copyright header, re-staging safely."""
    candidates = collect_staged_added_files(repo_root)
    missing = find_missing_copyright_files(repo_root, candidates)
    blocked: list[str] = []
    for rel in missing:
        if not _staged_matches_worktree(repo_root, rel):
            blocked.append(rel)
            continue
        if fix_files(repo_root, [rel], year=year, author=author):
            _run_git(repo_root, ["add", "--", rel], check=True)
            print(f"[copyright] added header and re-staged: {rel}")
    if blocked:
        for rel in blocked:
            print(
                f"error: staged file '{rel}' is missing copyright header and has unstaged edits; "
                f"run 'python3 tools/copyright_header.py --fix {rel}' and re-stage.",
                file=sys.stderr,
            )
        return 1
    return 0


def install_git_hook(repo_root: Path) -> int:
    """Configure git core.hooksPath to .githooks and ensure the pre-commit hook is executable."""
    hook = repo_root / ".githooks/pre-commit"
    if not hook.is_file():
        print(f"error: missing hook script at {hook}", file=sys.stderr)
        return 1
    mode = hook.stat().st_mode | 0o111
    hook.chmod(mode)
    _run_git(repo_root, ["config", "core.hooksPath", ".githooks"], check=True)
    print(f"Configured git core.hooksPath=.githooks for {repo_root}")
    return 0


def _resolve_target_paths(repo_root: Path, args: argparse.Namespace) -> list[str]:
    if args.paths:
        return [norm_rel(p, repo_root) for p in args.paths]
    if args.all:
        return collect_all_tracked_files(repo_root)
    return collect_added_files(repo_root, args.base, args.local)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Check and add GPL v2+ copyright headers.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="Fail if any target file lacks a header")
    mode.add_argument("--fix", action="store_true", help="Insert headers into target files missing one")
    mode.add_argument("--staged", action="store_true", help="Pre-commit mode: auto-fix cleanly staged new files")
    mode.add_argument("--install-hook", action="store_true", help="Configure git core.hooksPath=.githooks")
    parser.add_argument("--all", action="store_true", help="Target all tracked non-excluded files")
    parser.add_argument("--local", action="store_true", help="Target newly added local/untracked files")
    parser.add_argument("--base", default=DEFAULT_BASE, help="Git base ref for added files (with --check/--fix)")
    parser.add_argument("--year", type=int, default=None, help="Override copyright year (default: current year)")
    parser.add_argument("--author", default=DEFAULT_AUTHOR, help="Copyright holder string")
    parser.add_argument("paths", nargs="*", help="Explicit file paths to check or fix")
    args = parser.parse_args(argv)

    repo_root = Path(__file__).resolve().parents[1]
    if args.install_hook:
        return install_git_hook(repo_root)
    if args.staged:
        return handle_staged(repo_root, year=args.year, author=args.author)

    targets = _resolve_target_paths(repo_root, args)
    if args.check:
        missing = find_missing_copyright_files(repo_root, targets)
        for rel in missing:
            print(f"[copyright] missing header: {rel}")
        print(f"copyright: checked {len(targets)} file(s) -> {len(missing)} missing")
        return 1 if missing else 0

    modified = fix_files(repo_root, targets, year=args.year, author=args.author)
    print(f"copyright: added header to {len(modified)} of {len(targets)} target file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
